#!/usr/bin/env python3
"""Generate a portable patch-code fingerprint; startup UI changes do not repatch games."""
import argparse
import hashlib
from pathlib import Path
root=Path(__file__).resolve().parents[1]
files=sorted((root/'switch/managed').glob('*Patches.cs'))+[root/'switch/managed/StreamedAudio.cs',root/'switch/managed/DialogueClock.cs',root/'switch/managed/DetailProfiler.cs',root/'switch/managed/SwitchMixer.cs',root/'switch/managed/SwitchRaster.cs',root/'switch/managed/PlatformGameBridge.cs',root/'switch/managed/PatchValidation.cs',root/'switch/managed/FrameProfiler.cs',root/'switch/managed/StartupMetrics.cs']
content=''.join(str(p.relative_to(root)).replace('\\','/')+'\n'+p.read_text(encoding='utf-8')+'\n' for p in files)
digest=hashlib.sha256(content.encode()).hexdigest()
text='// Generated by tools/update_patch_identity.py; do not edit by hand.\nnamespace WogSwitch;\ninternal static class PatchIdentity { internal const string Value = "'+digest+'"; }\n'
target=root/'switch/managed/PatchIdentity.cs'
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
if args.check:
    if not target.exists() or target.read_text()!=text:raise SystemExit('Patch sources changed; run python3 tools/update_patch_identity.py and commit PatchIdentity.cs')
else:target.write_text(text)
print('PASS patch-code fingerprint '+digest)
